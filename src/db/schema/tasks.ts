import { integer, pgTable, text, timestamp } from "drizzle-orm/pg-core";

/**
 * Tasks (see GLOSSARY.md). Only the Tasks module (src/tasks) reads or writes
 * this table.
 *
 * Planned and completed days are local calendar days (`YYYY-MM-DD` text),
 * not instants: "today" is the user's own day, sent by the browser. A Task is
 * done exactly when completed_day is set. Column types stay within Drizzle's
 * portable subset, like the settings table.
 *
 * seq records insertion order, which is the order Today lists Tasks in.
 * created_at cannot do that job: two Tasks added in the same millisecond get
 * the same timestamp on PGlite. It is generated by default (not always) so an
 * undone delete can put a Task back with its original seq, and so its place.
 * The desktop SQLite path (`selected`) would map it to an autoincrementing integer.
 */
export const tasks = pgTable("tasks", {
  id: text("id")
    .primaryKey()
    .$defaultFn(() => crypto.randomUUID()),
  seq: integer("seq").notNull().generatedByDefaultAsIdentity(),
  title: text("title").notNull(),
  details: text("details").notNull().default(""),
  plannedDay: text("planned_day").notNull(),
  completedDay: text("completed_day"),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
});
